public class Main_5 {
    public static void main(String[] args) {
        int a = 6; // 변수 선언 및 초기화
        int b = 4;
        System.out.println(a<b); // a는 b보다 작다
        System.out.println(a>b); // a는 b보다 크다
        System.out.println(a>=b); // a는 b이상
        System.out.println(a<=b); // a는 b이하
        System.out.println(a==b); // a는 b와 같다
        System.out.println(a!=b); // a는 b와 같지 않다
    }
}
