package session1_to_3;

public class Main_7 {
    public static void main(String[] args) {

        int a = 10; //변수 선언 및 초기화
        a += 5; System.out.println("a += 5 : " + a); // a = a+5 // a += 5 : 15 출력

        a -= 3; System.out.println("a -= 3 : " + a); // a = a-3 // a -= 3 : 12 출력

        a *= 2; System.out.println("a *= 2 : " + a); // a = a*2 // a *= 2 : 24 출력

        a /= 4; System.out.println("a /= 4 : " + a); // a = a/4 // a /= 4 : 6 출력

        a %= 5; System.out.println("a %= 5 : " + a); // a = a%5 // a %=5 : 1 출력

    }
}
