package session7;

public class Method2_1 {
    public static void main(String[] args) {
        int a = 5;
        int b = 3;

        int add = a+b;
        System.out.println(a + "+" + b + "= " + add);

        int min = a-b;
        System.out.println(a + "-" + b + "= " + min);

        int mult = a * b;
        System.out.println(a + "*" + b + "= " + mult);

        int div = a / b;
        System.out.println(a + "/" + b + "= " + div);
    }
}
