package session1_to_3;

public class Main_1 {
    public static void main(String[] args) {

        int a = 50; // 변수 선언 및 초기화
        int b = 15;

        System.out.println(a + b); // 출력
        System.out.println(a - b);
        System.out.println(a * b); // a 곱하기 b
        System.out.println(a / b); // a 나누기 b
        System.out.println(a % b); // a 나누기 b의 나머지

        System.out.println("Hello World"); // 문장을 출력. 이때 문장 양쪽을 큰 따옴표로 감쌈
        System.out.println("점수" + 20 + 50); // "점수"라는 문자열이 앞으로 나오므로 숫자 20과 50을 문자열로 인식합니다.

    }
}
