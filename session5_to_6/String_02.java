package session5_to_6;

public class String_02 {
    public static void main(String[] args) {
        System.out.println(1 + "안녕"); // 숫자열 + 문자열
        System.out.println(1 + "안녕" + 2); // 숫자열 + 문자열 + 문자열
        System.out.println("안녕" + 1 + 2); // 문자열 + 문자열 + 문자열
        System.out.println(1 + 2 + "안녕"); // 숫자열 + 숫자열 + 문자열
    }
}
